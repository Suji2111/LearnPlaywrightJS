// Different Types of Identifier Cases in JavaScript

// Camel Case - first word lowercase, each subsequent word capitalized
let myVariableName = "camelCase";
let studentName = "camelCase";
let getUserDetails = "camelCase";

// Pascal Case - every word starts with uppercase
let MyVariableName = "PascalCase";
let StudentName = "PascalCase";
let GetUserDetails = "PascalCase";

// Snake Case - all lowercase, words separated by underscores
let my_variable_name = "snake_case";
let student_name = "snake_case";
let get_user_details = "snake_case";

// Screaming Snake Case / Upper Snake Case - all uppercase, words separated by underscores
let MY_CONSTANT = "UPPER_SNAKE_CASE";
let MAX_VALUE = "UPPER_SNAKE_CASE";
let API_KEY = "UPPER_SNAKE_CASE";

// Kebab Case - all lowercase, words separated by hyphens (NOT valid for JS identifiers)
// let my-variable-name = "kebab-case"; // INVALID in JavaScript
// let student-name = "kebab-case"; // INVALID in JavaScript

// Screaming Kebab Case - all uppercase, words separated by hyphens (NOT valid for JS identifiers)
// let MY-VARIABLE-NAME = "SCREAMING-KEBAB-CASE"; // INVALID in JavaScript

// Hungarian Notation - prefix indicates type
let strName = "Hungarian notation";
let nCount = "Hungarian notation";
let bIsActive = "Hungarian notation";
let arrItems = "Hungarian notation";

// Flat Case - all lowercase, no separators
let myvariablename = "flatcase";
let studentname = "flatcase";
let getuserdetails = "flatcase";

// Upper Flat Case - all uppercase, no separators
let MYVARIABLENAME = "UPPERFLATCASE";
let STUDENTNAME = "UPPERFLATCASE";

// Train Case / HTTP Header Case - uppercase first letter of each word, separated by hyphens (NOT valid for JS identifiers)
// let My-Variable-Name = "train-case"; // INVALID in JavaScript

// Cobol Case - all uppercase, separated by hyphens (NOT valid for JS identifiers)
// let MY-VARIABLE-NAME = "COBOL-CASE"; // INVALID in JavaScript

// Alternating Case - alternates uppercase and lowercase (not a standard convention)
let mYvArIaBlEnAmE = "alternatingCase";

// Camel Snake Case - camelCase with underscores
let my_Variable_Name = "camel_Snake_Case";
let get_User_Details = "camel_Snake_Case";

// Pascal Snake Case - PascalCase with underscores
let My_Variable_Name = "Pascal_Snake_Case";
let Get_User_Details = "Pascal_Snake_Case";

// Common JavaScript conventions:
// Variables: camelCase
let userName = "camelCase";
let totalCount = "camelCase";

// Constants: UPPER_SNAKE_CASE
const PI_VALUE = 3.14159;
const DEFAULT_TIMEOUT = 3000;

// Classes/Constructors: PascalCase
// class UserProfile {} // PascalCase
// class DataManager {} // PascalCase

// Private fields: start with underscore (convention)
let _privateVariable = "convention for private";
let _internalData = "convention for private";

